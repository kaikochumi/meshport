import { build } from "esbuild";
import { stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(root, "chrome-extension/vendor/tripo_loader.js");

await build({
  entryPoints: [path.join(root, "tools/vendor-entry.js")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  external: ["node:fs", "node:path"],
  minify: true,
  legalComments: "none",
  banner: {
    js: "/* Generated by tools/build-vendor.mjs. Third-party licenses: THIRD_PARTY_NOTICES.md. */",
  },
});

const { size } = await stat(outfile);
console.log(`Wrote ${path.relative(root, outfile)} (${(size / 1024).toFixed(0)} KB)`);
